const normalize = (value: string) =>
  value.toLowerCase().replace(/\s+/g, " ").trim();

export const findMerchantLogoPreset = (name: string) => {
  const normalized = normalize(name || "");
  if (!normalized) return null;
  return (
    MERCHANT_LOGO_PRESETS.find((preset) =>
      preset.match.some((token) => normalized.includes(token))
    ) || null
  );
};

export const getPresetLogoUrl = (name: string) =>
  findMerchantLogoPreset(name)?.url || null;
