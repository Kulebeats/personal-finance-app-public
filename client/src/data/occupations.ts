// Flatten all occupations for search with category info
export const ALL_OCCUPATIONS = OCCUPATION_CATEGORIES.flatMap(
  (category) => 
    category.occupations.map(occupation => ({
      occupation,
      category: category.name,
      icon: category.icon
    }))
);

export interface OccupationSearchResult {
  occupation: string;
  category: string;
  icon: string;
}

// Search function
export function searchOccupations(query: string): OccupationSearchResult[] {
  if (!query) return ALL_OCCUPATIONS;

  const lowerQuery = query.toLowerCase();
  return ALL_OCCUPATIONS.filter((item) =>
    item.occupation.toLowerCase().includes(lowerQuery) ||
    item.category.toLowerCase().includes(lowerQuery)
  );
}
